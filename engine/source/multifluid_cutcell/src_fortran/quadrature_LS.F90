        psi(2) =-128.0*xi*(xi - 1.)*(xi - 3.0/4.)*(xi - 1.0/2.)/3.
        psi(3) = 64.0*xi*(xi - 1.)*(xi - 3.0/4.)*(xi - 1.0/4.)
        psi(4) =-128.0*xi*(xi - 1.)*(xi - 1.0/2.)*(xi - 1.0/4.)/3.
        psi(5) = 32.0*xi*(xi - 3.0/4.)*(xi - 1.0/2.)*(xi - 1.0/4.)/3.
    else if (N==5) then
        psi = (/-625.0*(xi - 1.)*(xi - 4.0/5.)*(xi - 3.0/5.)*(xi - 2.0/5.)*(xi - 1.0/5.)/24.,&
                3125.0*xi*(xi - 1.)*(xi - 4.0/5.)*(xi - 3.0/5.)*(xi - 2.0/5.)/24. ,&
