  subroutine basis1d(N, ndof, xi, psi)
    integer, intent(in) :: N, ndof
    real(wp), intent(in) :: xi
    real(wp), dimension(ndof), intent(out) :: psi
    
    if (N==0) then
        psi(1) = 1.
    else if (N==1) then
        psi(1) = 1. - xi
        psi(2) = xi
    else if (N==2) then
