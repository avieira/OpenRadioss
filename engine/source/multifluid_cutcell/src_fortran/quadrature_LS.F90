        psi(2) = 4.0*xi*(1.0 - xi)
        psi(3) = 2.0*xi*(xi - 0.5)
    else if (N==3) then
        psi(1) = -4.5*(xi - 1.0/3)*(xi - 2.0/3)*(xi - 1.0)
        psi(2) = 13.5*xi*(xi - 2.0/3)*(xi - 1.0)
        psi(3) = -13.5*xi*(xi - 1.0/3)*(xi - 1.0)
        psi(4) = 4.5*xi*(xi - 1.0/3)*(xi - 2.0/3)
    else if (N==4) then
