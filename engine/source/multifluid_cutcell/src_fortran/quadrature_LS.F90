                 972.0*xi*(xi - 1.)*(xi - 5.0/6.)*(xi - 1.0/2.)*(xi - 1.0/3.)*(xi - 1.0/6.) , &
                 -1944.0*xi*(xi - 1.)*(xi - 2.0/3.)*(xi - 1.0/2.)*(xi - 1.0/3.)*(xi - 1.0/6.)/5. , &
                 324.0*xi*(xi - 5.0/6.)*(xi - 2.0/3.)*(xi - 1.0/2.)*(xi - 1.0/3.)*(xi - 1.0/6.)/5. /)
    end if
  end subroutine basis1d
  
