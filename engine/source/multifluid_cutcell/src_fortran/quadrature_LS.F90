  !! \brief Quadrature nodes (xigp) and weights (wgp) on the reference interface [0,1] given the number of Gaussian points (ngp).
  subroutine quadrature(ngp, xigp, wgp) !ngp=number of quadrature points
    implicit none
    integer, intent(in) :: ngp
    real(wp), dimension(ngp), intent(out) :: xigp, wgp

    real(wp) :: a1, a2, a3

    if (ngp == 1) then
      xigp(1) = 0.5
      wgp(1) = 1.0
    else if (ngp ==2) then
      xigp(1) = 0.5 - sqrt(3.)/6.
      xigp(2) = 0.5 + sqrt(3.)/6.

      wgp(1) = 0.5
      wgp(2) = 0.5
    else if (ngp==3) then
      xigp(1) = 0.5 - sqrt(15.0)/10.0
      xigp(2) = 0.5
      xigp(3) = 0.5 + sqrt(15.0)/10.0

      wgp(1) = 5.0/18.0
      wgp(2) = 8.0/18.0
      wgp(3) = 5.0/18.0
    else if (ngp==4) then
      xigp(1) = 0.5 * (1.0 - 0.8611363116)
      xigp(2) = 0.5 * (1.0 - 0.3399810436)
      xigp(3) = 0.5 * (1.0 + 0.3399810436)
      xigp(4) = 0.5 * (1.0 + 0.8611363116)

      wgp(1) = 0.5 * 0.3478548451
      wgp(2) = 0.5 * 0.6521451549
      wgp(3) = 0.5 * 0.6521451549
      wgp(4) = 0.5 * 0.3478548451
    else if (ngp ==5) then
      a1 = 0.9061798459386640
      a2 = 0.5384693101056831
      xigp(1) = 0.5 * (1 - a1)
      xigp(2) = 0.5 * (1 - a2)
      xigp(3) = 0.5
      xigp(4) = 0.5 * (1 + a2)
      xigp(5) = 0.5 * (1 + a1)

      wgp(1) = 0.5 * 0.2369268850561891
      wgp(2) = 0.5 * 0.4786286704993665
      wgp(3) = 0.5 * 0.5688888888888889
      wgp(4) = 0.5 * 0.4786286704993665
      wgp(5) = 0.5 * 0.2369268850561891
    else if (ngp==6) then
      a1 = 0.9324695142031521
      a2 = 0.6612093864662645
      a3 = 0.2386191860831969
      xigp(1) = 0.5 * (1 - a1)
      xigp(2) = 0.5 * (1 - a2)
      xigp(3) = 0.5 * (1 - a3)
      xigp(4) = 0.5 * (1 + a3)
      xigp(5) = 0.5 * (1 + a2)
      xigp(6) = 0.5 * (1 + a1)

      wgp(1) = 0.5 * 0.1713244923791704
      wgp(2) = 0.5 * 0.3607615730481386
      wgp(3) = 0.5 * 0.4679139345726910
      wgp(4) = 0.5 * 0.4679139345726910
      wgp(5) = 0.5 * 0.3607615730481386
      wgp(6) = 0.5 * 0.1713244923791704
    else if (ngp == 7) then
      a1 = 0.9491079123427585
      a2 = 0.7415311855993945
      a3 = 0.4058451513773972
      xigp(1) = 0.5 * (1 - a1)
      xigp(2) = 0.5 * (1 - a2)
      xigp(3) = 0.5 * (1 - a3)
      xigp(4) = 0.5
      xigp(5) = 0.5 * (1 + a3)
      xigp(6) = 0.5 * (1 + a2)
      xigp(7) = 0.5 * (1 + a1)

      wgp(1) = 0.5 * 0.1294849661688697
      wgp(2) = 0.5 * 0.2797053914892766
      wgp(3) = 0.5 * 0.3818300505051189
      wgp(4) = 0.5 * 0.4179591836734694
      wgp(5) = 0.5 * 0.3818300505051189
      wgp(6) = 0.5 * 0.2797053914892766
      wgp(7) = 0.5 * 0.1294849661688697
    end if
  end subroutine quadrature

  !! \brief 1D DG basis.
